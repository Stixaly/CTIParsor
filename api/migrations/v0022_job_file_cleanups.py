"""Version 22 — `job_file_cleanups`, the files a deleted job still owns (#724).

A DELETE of a job removes its rows and its files.  The row of each file to remove is written
in the same transaction as the deletes, so a crash or a filesystem error after the commit
leaves a row that names the file: api/routes/jobs.py retries it at start-up, on each retention
sweep and on a DELETE of the same job id, and deletes the row once the file is gone.
`job_id` is not a foreign key: the job's row is the thing being deleted.  `path` is the
canonical path, under the uploads or output directory; `attempts` and `last_error` tell an
operator what has failed.  Process bookkeeping, not report data: no table of the reports refers
to it, so an older release that does not write it keeps working."""
from api.migrations import Migration, columns_exist, tables_exist

MIGRATION = Migration(
    version=22,
    name="job_file_cleanups",
    store="jobs",
    description="job_file_cleanups: the files of a deleted job that are not removed yet",
    is_applied=lambda conn: (
        tables_exist(conn, "job_file_cleanups")
        and columns_exist(conn, "job_file_cleanups", "id", "job_id", "path", "attempts", "last_error",
                          "created_at", "updated_at")),
    statements=(
        "CREATE TABLE IF NOT EXISTS job_file_cleanups ("
        " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
        " job_id TEXT NOT NULL,"
        " path TEXT NOT NULL,"
        " attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),"
        " last_error TEXT,"
        " created_at TEXT NOT NULL,"
        " updated_at TEXT NOT NULL,"
        " UNIQUE (job_id, path))",
    ),
)
